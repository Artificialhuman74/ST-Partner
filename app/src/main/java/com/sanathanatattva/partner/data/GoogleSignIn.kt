package com.sanathanatattva.partner.data

import android.annotation.SuppressLint
import android.content.Context
import androidx.credentials.ClearCredentialStateRequest
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import androidx.credentials.exceptions.GetCredentialException
import androidx.credentials.exceptions.NoCredentialException
import com.google.android.libraries.identity.googleid.GetGoogleIdOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.firebase.FirebaseApp
import com.google.firebase.auth.FirebaseAuth
import com.google.firebase.auth.GoogleAuthProvider
import kotlinx.coroutines.CancellationException
import kotlinx.coroutines.tasks.await

/**
 * Google account → Firebase ID token, which the website verifies in
 * `POST /api/auth/partner/google` (same Firebase project as the website's Google sign-in).
 */
class GoogleSignIn(private val appContext: Context) {

    sealed interface Outcome {
        data class Token(val firebaseIdToken: String) : Outcome
        data object Cancelled : Outcome
        data object NoGoogleAccount : Outcome
        /** google-services.json isn't in the build yet (handoff §8 item 2). */
        data object NotConfigured : Outcome
        data object Failed : Outcome
    }

    // Generated by the google-services plugin from google-services.json; absent without it,
    // so it's looked up by name instead of R.string to keep the build working either way.
    @SuppressLint("DiscouragedApi")
    private fun webClientId(): String? {
        val id = appContext.resources.getIdentifier("default_web_client_id", "string", appContext.packageName)
        return if (id == 0) null else appContext.getString(id).takeIf { it.isNotBlank() }
    }

    private fun firebaseReady() = FirebaseApp.getApps(appContext).isNotEmpty()

    /** [activityContext] must be an Activity context: the account picker is shown over it. */
    suspend fun signIn(activityContext: Context): Outcome {
        val clientId = webClientId()
        if (clientId == null || !firebaseReady()) return Outcome.NotConfigured
        val request = GetCredentialRequest.Builder()
            .addCredentialOption(
                GetGoogleIdOption.Builder()
                    .setFilterByAuthorizedAccounts(false)
                    .setServerClientId(clientId)
                    .setAutoSelectEnabled(false)
                    .build(),
            )
            .build()
        return try {
            val credential = CredentialManager.create(activityContext).getCredential(activityContext, request).credential
            if (credential !is CustomCredential || credential.type != GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
                return Outcome.Failed
            }
            val google = GoogleIdTokenCredential.createFrom(credential.data)
            val user = FirebaseAuth.getInstance()
                .signInWithCredential(GoogleAuthProvider.getCredential(google.idToken, null))
                .await()
                .user ?: return Outcome.Failed
            user.getIdToken(true).await().token?.let(Outcome::Token) ?: Outcome.Failed
        } catch (e: CancellationException) {
            throw e
        } catch (_: GetCredentialCancellationException) {
            Outcome.Cancelled
        } catch (_: NoCredentialException) {
            Outcome.NoGoogleAccount
        } catch (_: GetCredentialException) {
            Outcome.Failed
        } catch (_: Exception) {
            Outcome.Failed
        }
    }

    /** A fresh Firebase ID token for the Google account still signed in (joining with Google). */
    suspend fun currentIdToken(): String? {
        if (!firebaseReady()) return null
        val user = FirebaseAuth.getInstance().currentUser ?: return null
        return runCatching { user.getIdToken(true).await().token }.getOrNull()
    }

    /** Email and name of the Google account still signed in, to prefill signup. */
    fun currentAccount(): Pair<String?, String?>? {
        if (!firebaseReady()) return null
        val user = FirebaseAuth.getInstance().currentUser ?: return null
        return user.email to user.displayName
    }

    /** Forget the Google choice too, so the next login asks which account. */
    suspend fun signOut() {
        if (firebaseReady()) runCatching { FirebaseAuth.getInstance().signOut() }
        runCatching { CredentialManager.create(appContext).clearCredentialState(ClearCredentialStateRequest()) }
    }
}
